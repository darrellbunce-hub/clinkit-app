/**
 * Verify SECURITY DEFINER ACL remediation targets are service_role-only.
 *
 * Authoritative target catalogue:
 *   scripts/secdef-service-role-only-targets.json
 *
 * This verifier derives the check set from that JSON (not a hard-coded count).
 * The companion .sql file is regenerated from the same catalogue for SQL Editor use.
 *
 * Usage (linked Supabase project; read-only catalog query):
 *   node scripts/verify-secdef-acl-remediation.mjs
 *
 * Optional:
 *   node scripts/verify-secdef-acl-remediation.mjs --sql-only
 *   node scripts/verify-secdef-acl-remediation.mjs --write-sql
 *
 * Exit 0 only when every catalogue target is PASS (anon/authenticated/public EXECUTE
 * false, service_role EXECUTE true) and the returned row count matches the catalogue.
 */

import { spawnSync } from "child_process";
import { existsSync, readFileSync, writeFileSync, unlinkSync } from "fs";
import { tmpdir } from "os";
import { join, resolve } from "path";

const targetsPath = resolve("scripts/secdef-service-role-only-targets.json");
const sqlPath = resolve("scripts/verify-secdef-acl-remediation.sql");

if (!existsSync(targetsPath)) {
  console.error(`Missing ${targetsPath}`);
  process.exit(1);
}

const targetsDoc = JSON.parse(readFileSync(targetsPath, "utf8"));
const targets = Array.isArray(targetsDoc.targets) ? targetsDoc.targets : [];
const expectedCount = targets.length;

if (expectedCount === 0) {
  console.error("Catalogue has zero targets");
  process.exit(1);
}

function regprocText(entry) {
  const schema = entry.schema || "public";
  const name = entry.name;
  const args = (entry.args ?? "").trim();
  // to_regprocedure expects compact type lists without spaces after commas.
  const compactArgs = args
    ? args
        .split(",")
        .map((part) => part.trim())
        .join(",")
    : "";
  return `${schema}.${name}(${compactArgs})`;
}

function buildVerifierSql(entries) {
  const values = entries
    .map((entry) => `    ('${regprocText(entry).replace(/'/g, "''")}')`)
    .join(",\n");

  return `-- SEC: Verify remediation targets are service_role-only (read-only).
-- Authoritative catalogue: scripts/secdef-service-role-only-targets.json
-- Generated by: node scripts/verify-secdef-acl-remediation.mjs --write-sql
-- Expect: every listed function has anon=false, authenticated=false, public=false, service_role=true.
-- Target count: ${entries.length}
-- Run via:
--   node scripts/verify-secdef-acl-remediation.mjs
--   npx supabase db query --linked -f scripts/verify-secdef-acl-remediation.sql -o json

with targets(regproc_text) as (
  values
${values}
),
resolved as (
  select
    t.regproc_text as function,
    to_regprocedure(t.regproc_text) as oid
  from targets t
)
select
  r.function,
  case when r.oid is null then null else has_function_privilege('anon', r.oid, 'EXECUTE') end as anon,
  case when r.oid is null then null else has_function_privilege('authenticated', r.oid, 'EXECUTE') end as authenticated,
  case when r.oid is null then null else has_function_privilege('service_role', r.oid, 'EXECUTE') end as service_role,
  case when r.oid is null then null else has_function_privilege('public', r.oid, 'EXECUTE') end as public_execute,
  case
    when r.oid is null then 'FAIL_MISSING'
    when has_function_privilege('anon', r.oid, 'EXECUTE') then 'FAIL'
    when has_function_privilege('authenticated', r.oid, 'EXECUTE') then 'FAIL'
    when has_function_privilege('public', r.oid, 'EXECUTE') then 'FAIL'
    when not has_function_privilege('service_role', r.oid, 'EXECUTE') then 'FAIL'
    else 'PASS'
  end as status
from resolved r
order by r.function;
`;
}

const sqlText = buildVerifierSql(targets);

if (process.argv.includes("--sql-only")) {
  process.stdout.write(sqlText);
  process.exit(0);
}

if (process.argv.includes("--write-sql")) {
  writeFileSync(sqlPath, sqlText, "utf8");
  console.log(`Wrote ${sqlPath} (${expectedCount} targets from catalogue)`);
  process.exit(0);
}

console.log("SECURITY DEFINER ACL remediation verifier");
console.log("=========================================");
console.log(`Expected targets: ${expectedCount}`);
console.log(`Catalogue: scripts/secdef-service-role-only-targets.json`);
console.log(`Migration: ${targetsDoc.migration ?? "(unknown)"}`);
console.log("");

const tmp = join(tmpdir(), `secdef-acl-verify-${Date.now()}.sql`);
writeFileSync(tmp, sqlText, "utf8");

let result;
try {
  result = spawnSync(
    "npx",
    ["supabase", "db", "query", "--linked", "-f", tmp, "-o", "json"],
    {
      encoding: "utf8",
      shell: true,
      maxBuffer: 10 * 1024 * 1024,
    }
  );
} finally {
  try {
    unlinkSync(tmp);
  } catch {
    // ignore
  }
}

if (result.status !== 0) {
  console.error(result.stderr || result.stdout || "supabase db query failed");
  process.exit(1);
}

const raw = `${result.stdout || ""}${result.stderr || ""}`;
const start = raw.indexOf("{");
const end = raw.lastIndexOf("}");
if (start < 0 || end < 0) {
  console.error("Could not parse JSON from supabase db query output");
  console.error(raw.slice(0, 2000));
  process.exit(1);
}

let payload;
try {
  payload = JSON.parse(raw.slice(start, end + 1));
} catch (error) {
  console.error("Invalid JSON from supabase db query:", error.message);
  process.exit(1);
}

const rows = payload?.rows;
if (!Array.isArray(rows) || rows.length === 0) {
  console.error("No rows returned from remediation verifier SQL");
  process.exit(1);
}

const nameWidth = Math.max(
  12,
  ...rows.map((row) => String(row.function ?? "").length)
);

console.log(
  `${"function".padEnd(nameWidth)}  anon  auth  service  public  status`
);
console.log("-".repeat(nameWidth + 42));

let failures = 0;
for (const row of rows) {
  const status = String(row.status ?? "FAIL");
  if (status !== "PASS") failures += 1;
  const anon = row.anon === null || row.anon === undefined ? "-" : String(row.anon);
  const auth =
    row.authenticated === null || row.authenticated === undefined
      ? "-"
      : String(row.authenticated);
  const service =
    row.service_role === null || row.service_role === undefined
      ? "-"
      : String(row.service_role);
  const pub =
    row.public_execute === null || row.public_execute === undefined
      ? "-"
      : String(row.public_execute);
  console.log(
    `${String(row.function).padEnd(nameWidth)}  ${anon.padEnd(4)}  ${auth.padEnd(4)}  ${service.padEnd(7)}  ${pub.padEnd(6)}  ${status}`
  );
}

console.log("-".repeat(nameWidth + 42));
console.log(`Rows: ${rows.length}  Failures: ${failures}`);

if (rows.length !== expectedCount) {
  console.error(
    `Row count mismatch: expected ${expectedCount} from catalogue, got ${rows.length}`
  );
  process.exit(1);
}

if (failures > 0) {
  console.error(
    "FAIL: one or more remediation targets still allow anon/authenticated/public EXECUTE, lack service_role EXECUTE, or are missing."
  );
  process.exit(1);
}

console.log(
  `PASS: all ${expectedCount} remediation targets are service_role-only.`
);
process.exit(0);
